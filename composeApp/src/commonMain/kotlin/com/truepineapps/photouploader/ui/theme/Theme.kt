/**
 * A data class representing a cohesive family of colors used in Material Design theming.
 *
 * This structure groups a primary tone with its associated "on" color (for text/icons
 * placed on top of the primary tone), a container variant, and an "on" color for
 * that container. This pattern allows for consistent color definition across custom
 * color roles that fall outside standard MaterialTheme slots.
 *
 * @property color The main color of this family.
 * @property onColor The color used for content (text/icons) displayed on top of [color].
 * @property colorContainer A tonal variation of the main color, usually used for less prominent containers.
 * @property onColorContainer The color used for content displayed on top of [colorContainer].
 */
@Immutable
data class ColorFamily(
    val color: Color,
    val onColor: Color,
    val colorContainer: Color,
    val onColorContainer: Color
)

val unspecified_scheme = ColorFamily(
    Color.Unspecified, Color.Unspecified, Color.Unspecified, Color.Unspecified
)

// Dynamic color is only available on Android 12+, no multiplatform support
@Composable
fun AppTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    contrastLevel:ContrastLevel = getSystemContrastLevel(),
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        // Handle Dark Mode permutations
        darkTheme && contrastLevel == ContrastLevel.High -> highContrastDarkColorScheme
        darkTheme && contrastLevel == ContrastLevel.Medium -> mediumContrastDarkColorScheme
        darkTheme -> darkScheme

        // Handle Light Mode permutations
        contrastLevel == ContrastLevel.High -> highContrastLightColorScheme
        contrastLevel == ContrastLevel.Medium -> mediumContrastLightColorScheme
        else -> lightScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = getAppTypography(),
        content = content
    )
}
